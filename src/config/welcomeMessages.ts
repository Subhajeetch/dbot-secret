/**
 * Efficiently selects a random welcome message and replaces {user} with the member's mention.
 */
export function getRandomWelcomeMessage(userId: string): string {
  const index = Math.floor(Math.random() * welcomeMessages.length);
  const template = welcomeMessages[index];
  return template.replace("{user}", `<@${userId}>`);
}
